/* USER CODE BEGIN 0 */
void PID_Calc(PID *pid, float current_rpm)
{
    pid->error = pid->target - current_rpm;
    pid->integral += pid->error;

    if (pid->integral > 500.0f) pid->integral = 500.0f;
    if (pid->integral < -100.0f) pid->integral = -100.0f;

    float output = 275.0f;
    output += pid->Kp * pid->error;
    output += pid->Ki * pid->integral;
    output += pid->Kd * (pid->error - pid->last_error);

    if (output > 900.0f) output = 900.0f;
    if (output < 0.0f)   output = 0.0f;

    pid->output = output;
    pid->last_error = pid->error;
}
