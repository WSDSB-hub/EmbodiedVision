	      int32_t left_now = __HAL_TIM_GET_COUNTER(&htim3);
	      int32_t left_delta = left_now - left_last;
	      left_last = left_now;

	      if (left_delta > 80 || left_delta < -80) {
	          left_delta = 0;
	      }
