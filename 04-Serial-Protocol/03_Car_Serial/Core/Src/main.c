/* USER CODE BEGIN 0 */
void PID_Calc(PID *p, float current)
{
    if (p->target == 0.0f) {
        p->output = 0.0f;
        p->integral = 0.0f;
        p->last_error = 0.0f;
        return;
    }

    p->error = p->target - current;
    p->integral += p->error;
    if (p->integral > 500.0f) p->integral = 500.0f;
    if (p->integral < -100.0f) p->integral = -100.0f;

    float output = 275.0f;
    output += p->Kp * p->error;
    output += p->Ki * p->integral;
    output += p->Kd * (p->error - p->last_error);
    if (output > 900.0f) output = 900.0f;
    if (output < 0.0f)   output = 0.0f;

    p->output = output;
    p->last_error = p->error;
}

// 指令解析（统一用 pid）
void Parse_Command(void)
{
  if (uart_rx_complete)
  {
    uart_rx_complete = 0;
    uint8_t cmd = uart_rx_buf[1];
    int16_t left_speed = (uart_rx_buf[2] << 8) | uart_rx_buf[3];
    int16_t right_speed = (uart_rx_buf[4] << 8) | uart_rx_buf[5];

    switch (cmd)
    {
      case 0x01:
        pid.target = left_speed;
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_2, GPIO_PIN_SET);
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_3, GPIO_PIN_RESET);
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_SET);
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);
        break;
      case 0x05:
        pid.target = 0;
        break;
    }
  }
}
